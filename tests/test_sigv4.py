"""SigV4 presigning must match aws-iot-device-sdk-js byte for byte."""

from datetime import UTC, datetime

from custom_components.hatch_rest.api.sigv4 import presign_websocket_path, signing_key


def test_signing_key_matches_aws_documentation_vector():
    # https://docs.aws.amazon.com/general/latest/gr/signature-v4-examples.html
    key = signing_key("wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY", "20120215", "us-east-1", "iam")
    assert key.hex() == "f4780e2d9f65fa895f9c67b32ce1baf0b0d8a43505a000a1a9e090d414db404d"


def test_presigned_path_matches_node_sdk():
    # Expected value generated by running prepareWebSocketUrl from
    # aws-iot-device-sdk@2.2.16 (what the homebridge plugin uses) with the
    # same inputs and a frozen clock
    path = presign_websocket_path(
        "abc123-ats.iot.us-east-1.amazonaws.com",
        "us-east-1",
        "ASIAEXAMPLEKEY",
        "wJalrXUtnFEMI/K7MDENG+bPxRfiCYEXAMPLEKEY",
        "FwoGZX+IvYXdz/EH=token",
        now=datetime(2026, 10, 12, 15, 4, 5, tzinfo=UTC),
    )
    assert path == (
        "/mqtt?X-Amz-Algorithm=AWS4-HMAC-SHA256"
        "&X-Amz-Credential=ASIAEXAMPLEKEY%2F20261012%2Fus-east-1%2Fiotdevicegateway%2Faws4_request"
        "&X-Amz-Date=20261012T150405Z&X-Amz-SignedHeaders=host"
        "&X-Amz-Signature=468262e1b56b9fe0da1832ad00a70695390bbe88ddc23876cb004f1ab46b11c6"
        "&X-Amz-Security-Token=FwoGZX%2BIvYXdz%2FEH%3Dtoken"
    )
